#!/usr/bin/env python3
"""Builds dist/home-panel-cards.js — one file containing every card, loaded by Home Assistant via HACS."""
import os
D = os.path.dirname(os.path.abspath(__file__))
src = lambda f: open(os.path.join(D, 'src', f), encoding='utf-8').read()
def rep(s, x, y):
    assert s.count(x) == 1, x
    return s.replace(x, y)
def cut(s, start, end):
    a = s.index(start); b = s.index(end, a)
    return s[:a], s[a + len(start):b], s[b + len(end):]

# the panel card keeps its two style sheets inline in the source; split them out into globals
p = src('home-panel-card.js')
pre, css, post = cut(p, 'const CSS = `', '\n`;\n')
main = pre + post
pre, css2, post = cut(main, 'const PPLCSS = `', '`;\n')
main = pre + post
main = rep(main, '<style>${CSS}</style>', "<style>${window.__HPC_CSS || ''}</style>")
main = rep(main, '<style>${PPLCSS}</style>', "<style>${window.__HPC_CSS2 || ''}</style>")
parts = [
    ('styles', "window.__HPC_CSS = `" + css + "\n`;\nwindow.__HPC_CSS2 = `" + css2 + "`;"),
    ('home-panel-card', main),
    ('pop-ups', src('hpc-pops.js')),
    ('home-lights-card', src('home-lights-card.js')),
    ('home-security-card', src('home-security-card.js')),
    ('home-energy-card', src('home-energy-card.js')),
    ('home-music-card', src('home-music-card.js')),
    ('home-room-card', src('home-room-card.js')),
]
out = '/* Home Panel Cards — built from src/ by build.py. Do not edit this file directly. */\n'
out += ''.join(f'\n/* ===== {n} ===== */\n(() => {{\n{c}\n}})();\n' for n, c in parts)
open(os.path.join(D, 'dist', 'home-panel-cards.js'), 'w', encoding='utf-8').write(out)
print('dist/home-panel-cards.js', len(out.encode()), 'bytes')
